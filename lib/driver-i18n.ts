/** Traduit une clé ; retombe sur le français puis sur la clé elle-même (jamais d'exception). */
export function tr(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const dict = (lang === 'ar' ? AR : FR) as Record<string, string>
  let s = dict[key] ?? (FR as Record<string, string>)[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** Langue initiale : langue du livreur (driver.lang) puis langue du navigateur, sinon français. */
export function detectLang(driverLang?: string | null, navLang?: string | null): Lang {
  const norm = (x?: string | null): Lang | null => {
    const v = (x ?? '').toLowerCase()
    if (v.startsWith('ar')) return 'ar'
    if (v.startsWith('fr')) return 'fr'
    return null
  }
  return norm(driverLang) ?? norm(navLang) ?? 'fr'
}
